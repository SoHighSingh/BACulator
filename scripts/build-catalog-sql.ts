/**
 * Generates the D1 seed migration for DrinkCatalog and ServeSize from src/lib/drinks.
 *
 *   npm run db:catalog-sql            # rewrites migrations/0003_seed_catalog.sql
 *   npm run db:catalog-sql -- 0004_reseed_catalog.sql   # new migration after editing the catalog
 */
import { writeFileSync } from "node:fs";

import { CATALOG } from "../src/lib/drinks/catalog";
import { SERVE_SIZES } from "../src/lib/drinks/serves";

const sql = (v: string | number | boolean | null | undefined) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") return v ? "1" : "0";
  if (typeof v === "number") return String(v);
  return `'${v.replace(/'/g, "''")}'`;
};

const ids = new Set<string>();
for (const e of CATALOG) {
  if (ids.has(e.id)) throw new Error(`Duplicate catalog id ${e.id}`);
  ids.add(e.id);
}

const lines = [
  "-- Generated by scripts/build-catalog-sql.ts from src/lib/drinks/catalog.ts and serves.ts. Do not edit by hand.",
  "-- Sources are cited in those files and in each row's sourceUrl.",
  'DELETE FROM "DrinkCatalog";',
  'DELETE FROM "ServeSize";',
  "",
  ...CATALOG.map(
    (e) =>
      `INSERT INTO "DrinkCatalog" ("id","name","brand","category","abv","serveMl","aliases","isMixer","sourceUrl") VALUES (${[
        e.id, e.name, e.brand, e.category, e.abv, e.serveMl, JSON.stringify(e.aliases), !!e.isMixer, e.sourceUrl,
      ].map(sql).join(",")});`,
  ),
  "",
  ...SERVE_SIZES.map(
    (s) =>
      `INSERT INTO "ServeSize" ("id","name","kind","volumeMl","categoryMl","impliesCategory","aliases","sourceUrl") VALUES (${[
        s.id, s.name, s.kind, s.volumeMl, s.categoryMl ? JSON.stringify(s.categoryMl) : null, s.impliesCategory ?? null,
        JSON.stringify(s.aliases), s.sourceUrl,
      ].map(sql).join(",")});`,
  ),
  "",
];

const name = process.argv[2] ?? "0003_seed_catalog.sql";
const out = new URL(`../migrations/${name}`, import.meta.url);
writeFileSync(out, lines.join("\n"));
console.log(`Wrote migrations/${name}: ${CATALOG.length} drinks, ${SERVE_SIZES.length} serve sizes`);
